create table if not exists public.suppliers (
  id bigint generated by default as identity primary key,
  name text not null unique,
  contact text not null default '',
  phone text not null default '',
  lead_time_days integer not null default 3,
  status text not null default 'Aktif' check (status in ('Aktif', 'Review', 'Nonaktif')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.sales_transactions (
  id bigint generated by default as identity primary key,
  outlet_id bigint not null references public.outlets(id) on delete cascade,
  transaction_number text not null unique,
  payment_method text not null check (payment_method in ('QRIS', 'Tunai', 'Debit')),
  subtotal numeric not null default 0,
  tax numeric not null default 0,
  total numeric not null default 0,
  cashier_id bigint references public.app_users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.sales_transaction_items (
  id bigint generated by default as identity primary key,
  transaction_id bigint not null references public.sales_transactions(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete restrict,
  product_name text not null,
  qty numeric not null check (qty > 0),
  unit_price numeric not null default 0,
  unit_cost numeric not null default 0,
  line_total numeric not null default 0
);

create index if not exists sales_transactions_outlet_date_idx on public.sales_transactions(outlet_id, created_at desc);
create index if not exists sales_transaction_items_transaction_idx on public.sales_transaction_items(transaction_id);


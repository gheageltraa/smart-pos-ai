create or replace function public.decrement_product_stock()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  bundle boolean;
  transaction_number text;
begin
  select sales.transaction_number into transaction_number
  from public.sales
  where sales.id = new.sale_id;

  if transaction_number like 'DEMO-%' then
    return new;
  end if;

  select is_bundle into bundle
  from public.products
  where id = new.product_id;

  if coalesce(bundle, false) then
    update public.products component
    set stock = greatest(0, component.stock - (items.quantity * new.qty)),
        updated_at = now()
    from public.bundle_items items
    where items.bundle_product_id = new.product_id
      and component.id = items.component_product_id;
  else
    update public.products
    set stock = greatest(0, stock - new.qty), updated_at = now()
    where id = new.product_id;
  end if;

  return new;
end;
$$;

drop trigger if exists sale_item_decrements_stock on public.sale_items;
create trigger sale_item_decrements_stock
after insert on public.sale_items
for each row execute function public.decrement_product_stock();

create or replace function public.create_pos_sale(
  p_outlet_id bigint,
  p_transaction_number text,
  p_payment_method text,
  p_cash_received numeric,
  p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  item_record record;
  stock_record public.products%rowtype;
  product_record public.products%rowtype;
  sale_id bigint;
  subtotal numeric := 0;
  tax numeric;
  tax_rate numeric := 0;
  total numeric;
begin
  if auth.uid() is null or not exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role in ('admin', 'kasir')
  ) then
    raise exception 'An authenticated POS account is required';
  end if;

  if p_items is null
    or jsonb_typeof(p_items) is distinct from 'array'
    or jsonb_array_length(p_items) = 0 then
    raise exception 'A sale must contain at least one item';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_items) as item("productId" bigint, qty numeric)
    where item.qty is null or item.qty <= 0
  ) then
    raise exception 'Sale quantities must be positive';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_items) as item("productId" bigint, qty numeric)
    left join public.products product
      on product.id = item."productId" and product.outlet_id = p_outlet_id
    where product.id is null
  ) then
    raise exception 'A sale item is not available at this outlet';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_items) as item("productId" bigint, qty numeric)
    join public.products bundle
      on bundle.id = item."productId" and bundle.outlet_id = p_outlet_id
    where bundle.is_bundle
      and not exists (
        select 1 from public.bundle_items
        where bundle_product_id = bundle.id
      )
  ) then
    raise exception 'A bundle must contain at least one component';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_items) as item("productId" bigint, qty numeric)
    join public.products bundle
      on bundle.id = item."productId" and bundle.outlet_id = p_outlet_id
    join public.bundle_items bundle_item
      on bundle_item.bundle_product_id = bundle.id
    join public.products component
      on component.id = bundle_item.component_product_id
    where bundle.is_bundle and component.outlet_id <> p_outlet_id
  ) then
    raise exception 'Bundle components must belong to the selected outlet';
  end if;

  for item_record in
    with requested as (
      select item."productId" as product_id, sum(item.qty) as qty
      from jsonb_to_recordset(p_items) as item("productId" bigint, qty numeric)
      group by item."productId"
    ),
    stock_demand as (
      select product.id as stock_product_id, requested.qty
      from requested
      join public.products product
        on product.id = requested.product_id
       and product.outlet_id = p_outlet_id
      where not product.is_bundle
      union all
      select component.id, requested.qty * bundle_item.quantity
      from requested
      join public.products bundle
        on bundle.id = requested.product_id
       and bundle.outlet_id = p_outlet_id
       and bundle.is_bundle
      join public.bundle_items bundle_item
        on bundle_item.bundle_product_id = bundle.id
      join public.products component
        on component.id = bundle_item.component_product_id
       and component.outlet_id = p_outlet_id
    )
    select stock_product_id, sum(qty) as required_qty
    from stock_demand
    group by stock_product_id
    order by stock_product_id
  loop
    select * into stock_record
    from public.products
    where id = item_record.stock_product_id
    for update;

    if stock_record.stock < item_record.required_qty then
      raise exception 'Insufficient stock for one or more sale items';
    end if;
  end loop;

  select coalesce(sum(product.price * item.qty), 0)
  into subtotal
  from jsonb_to_recordset(p_items) as item("productId" bigint, qty numeric)
  join public.products product
    on product.id = item."productId" and product.outlet_id = p_outlet_id;

  select coalesce(sum(sales.tax) / nullif(sum(sales.subtotal), 0), 0)
  into tax_rate
  from public.sales
  where sales.outlet_id = p_outlet_id;

  tax := round(subtotal * tax_rate);
  total := subtotal + tax;

  if p_payment_method = 'Tunai'
    and (p_cash_received is null or p_cash_received < total) then
    raise exception 'Cash received is less than the sale total';
  end if;

  insert into public.sales (
    transaction_number, outlet_id, payment_method, subtotal, tax, total, created_by
  )
  values (
    p_transaction_number, p_outlet_id, p_payment_method, subtotal, tax, total, auth.uid()
  )
  returning id into sale_id;

  for item_record in
    select * from jsonb_to_recordset(p_items) as item("productId" bigint, qty numeric)
  loop
    select * into product_record
    from public.products
    where id = item_record."productId" and outlet_id = p_outlet_id;

    insert into public.sale_items (
      sale_id, product_id, product_name, qty, unit_price, unit_cost, line_total
    )
    values (
      sale_id,
      product_record.id,
      product_record.name,
      item_record.qty,
      product_record.price,
      product_record.cost,
      product_record.price * item_record.qty
    );
  end loop;

  return jsonb_build_object(
    'transaction_number', p_transaction_number,
    'subtotal', subtotal,
    'tax', tax,
    'total', total
  );
end;
$$;


-- Kopipintar Smart POS / Supabase setup
-- Run this file in Supabase SQL Editor before deploying.

create extension if not exists pgcrypto;

create table if not exists public.app_users (
  id bigint generated by default as identity primary key,
  open_id text not null unique,
  name text,
  email text,
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_signed_in timestamptz not null default now()
);

create table if not exists public.outlets (
  id bigint generated by default as identity primary key,
  name text not null,
  code text not null unique,
  city text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.outlet_members (
  id bigint generated by default as identity primary key,
  outlet_id bigint not null references public.outlets(id) on delete cascade,
  user_id bigint not null references public.app_users(id) on delete cascade,
  role text not null default 'cashier' check (role in ('manager', 'cashier')),
  created_at timestamptz not null default now(),
  unique (outlet_id, user_id)
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  outlet_id bigint not null references public.outlets(id) on delete cascade,
  name text not null,
  sku text not null,
  category text not null default 'Kopi',
  unit text not null default 'pcs',
  stock numeric not null default 0,
  min_stock numeric not null default 0,
  cost numeric not null default 0,
  price numeric not null default 0,
  supplier text not null default '',
  daily_sales numeric not null default 0,
  trend numeric not null default 0,
  emoji text not null default '📦',
  icon_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (outlet_id, sku)
);

create table if not exists public.purchase_orders (
  id bigint generated by default as identity primary key,
  outlet_id bigint not null references public.outlets(id) on delete cascade,
  order_number text not null,
  supplier text not null,
  status text not null default 'Draft' check (status in ('Draft', 'Dipesan', 'Diterima')),
  total numeric not null default 0,
  created_by bigint references public.app_users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (outlet_id, order_number)
);

create table if not exists public.purchase_order_items (
  id bigint generated by default as identity primary key,
  purchase_order_id bigint not null references public.purchase_orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  qty numeric not null,
  unit text not null,
  unit_cost numeric not null default 0,
  reason text not null default ''
);

create index if not exists products_outlet_idx on public.products(outlet_id);
create index if not exists outlet_members_user_idx on public.outlet_members(user_id);
create index if not exists purchase_orders_outlet_idx on public.purchase_orders(outlet_id);


-- Kopipintar Composite / Bundle Products migration
-- Run after schema.sql and functional_features.sql.

alter table public.products
  add column if not exists is_bundle boolean not null default false;

create table if not exists public.bundle_items (
  id bigint generated by default as identity primary key,
  bundle_product_id bigint not null references public.products(id) on delete cascade,
  component_product_id bigint not null references public.products(id) on delete restrict,
  quantity numeric not null check (quantity > 0),
  unique (bundle_product_id, component_product_id),
  check (bundle_product_id <> component_product_id)
);

create index if not exists bundle_items_bundle_idx on public.bundle_items(bundle_product_id);
create index if not exists bundle_items_component_idx on public.bundle_items(component_product_id);

alter table public.bundle_items enable row level security;
drop policy if exists "bundle_items_public_read" on public.bundle_items;
drop policy if exists "bundle_items_admin_write" on public.bundle_items;
create policy "bundle_items_public_read" on public.bundle_items for select to anon, authenticated using (true);
create policy "bundle_items_admin_write" on public.bundle_items for all to authenticated
  using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'))
  with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

create or replace function public.decrement_product_stock()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  bundle boolean;
begin
  select is_bundle into bundle from public.products where id = new.product_id;
  if coalesce(bundle, false) then
    update public.products component
    set stock = greatest(0, component.stock - (items.quantity * new.qty)), updated_at = now()
    from public.bundle_items items
    where items.bundle_product_id = new.product_id
      and component.id = items.component_product_id;
  else
    update public.products
    set stock = greatest(0, stock - new.qty), updated_at = now()
    where id = new.product_id;
  end if;
  return new;
end;
$$;

drop trigger if exists sale_item_decrements_stock on public.sale_items;
create trigger sale_item_decrements_stock
after insert on public.sale_items
for each row execute function public.decrement_product_stock();
